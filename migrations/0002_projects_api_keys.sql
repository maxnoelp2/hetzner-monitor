-- 0002: API keys (ADR-0007), Hetzner projects with envelope-encrypted tokens (ADR-0005),
-- discovered resources. See docs/design/data-model.md.

CREATE TABLE api_keys (
    id            uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id        uuid        NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    user_id       uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name          text        NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
    prefix        text        NOT NULL UNIQUE CHECK (prefix ~ '^[a-z0-9]{12}$'),
    -- SHA-256 of the full key; the key itself is never stored.
    key_hash      bytea       NOT NULL CHECK (length(key_hash) = 32),
    scopes        text[]      NOT NULL CHECK (cardinality(scopes) > 0 AND scopes <@ ARRAY['read', 'write', 'admin']),
    last_used_at  timestamptz,
    expires_at    timestamptz,
    revoked_at    timestamptz,
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX api_keys_org_id_idx ON api_keys (org_id);

CREATE TABLE hetzner_projects (
    -- Generated by the application: the id is the AAD of the token ciphertext.
    id                 uuid        PRIMARY KEY,
    org_id             uuid        NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    name               text        NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    token_ct           bytea       NOT NULL,
    token_dek_ct       bytea       NOT NULL,
    key_version        integer     NOT NULL,
    token_hint         text        NOT NULL CHECK (length(token_hint) <= 4),
    status             text        NOT NULL DEFAULT 'active'
                                   CHECK (status IN ('active', 'invalid_token', 'degraded', 'paused')),
    status_message     text,
    budget_share       real        NOT NULL DEFAULT 0.5 CHECK (budget_share BETWEEN 0.1 AND 0.9),
    rl_limit           integer,
    rl_remaining       integer,
    rl_reset_at        timestamptz,
    metrics_interval_s integer,
    last_fast_at       timestamptz,
    last_metrics_at    timestamptz,
    last_inventory_at  timestamptz,
    created_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (org_id, name)
);
CREATE INDEX hetzner_projects_org_id_idx ON hetzner_projects (org_id);

CREATE TABLE resources (
    id             uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    project_id     uuid        NOT NULL REFERENCES hetzner_projects (id) ON DELETE CASCADE,
    kind           text        NOT NULL CHECK (kind IN ('server', 'load_balancer', 'volume', 'certificate',
                                                        'floating_ip', 'primary_ip')),
    hetzner_id     bigint      NOT NULL,
    name           text        NOT NULL DEFAULT '',
    labels         jsonb       NOT NULL DEFAULT '{}',
    snapshot       jsonb       NOT NULL,
    first_seen_at  timestamptz NOT NULL DEFAULT now(),
    last_seen_at   timestamptz NOT NULL DEFAULT now(),
    deleted_at     timestamptz,
    UNIQUE (project_id, kind, hetzner_id)
);
CREATE INDEX resources_project_kind_idx ON resources (project_id, kind);
